from telegram import ReplyKeyboardMarkup


def make_keyboard(rows):
    return ReplyKeyboardMarkup(
        rows,
        resize_keyboard=True,
    )


# ==================================================
# واجهة المستخدم
# ==================================================

def user_keyboard(is_admin_user=False):
    rows = [
        ["📖 القرآن والثقافة"],
        ["📚 الملازم"],
        ["🎧 المحاضرات"],
        ["ℹ️ عن البوت"],
    ]

    if is_admin_user:
        rows.append(["⚙️ الإدارة"])

    return make_keyboard(rows)


